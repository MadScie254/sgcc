        f"| Date range | 1 Jan 2014 – 31 Oct 2016 | {i['first_date']} – {i['last_date']} | ✓ | |",
        f"| Total records | ~43,850,520 | {i['cells']:,} customer-days | ✗ | {i['customers']:,} × {i['days']:,} |",
        f"| File format | CSV | CSV, {i['layout']} | ✓ | |",
        f"| File size | ~450 MB compressed | {i['file_size_mb']} MB uncompressed | ✗ | |",
        f"| Columns present | 4 (ID, Date, Consumption, Label) | {i['days'] + 2:,} | ✗ | Wide layout, not long |",
        "",
        "## II. Data completeness assessment",
        "",
        "| Completeness metric | Threshold | Actual | Pass/Fail | Action |",
        "|---|---|---|---|---|",
        f"| Missing values | < 0.1% | {c['missing_percent']}% ({c['missing_cells']:,} cells) | Fail | Keep as signal; impute only for methods that need complete rows |",
        f"| Customers with complete records | > 99% | {c['customers_complete']:,} ({pct(c['customers_complete'], i['customers'])}) | Fail | As above |",
        f"| Temporal continuity | All 1,035 days | {i['days']:,} days | Fail | {', '.join(i['absent_dates']) or '-'} absent from the release |",
        f"| Label completeness | 100% | {pct(i['customers'] - c['labels_missing'], i['customers'])} | Pass | |",
