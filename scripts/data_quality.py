def main() -> None:
    config = load_config()
    path = ROOT / config["data"]["training_data_path"]
    report = assess(path, {**DEFAULT_CLEANING_CONFIG, **config.get("preprocessing", {})})
    (ROOT / "artifacts" / "data_quality.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    (ROOT / "docs" / "data-quality.md").write_text(markdown(report), encoding="utf-8")
    print(json.dumps({k: report[k] for k in ("completeness", "class_distribution", "outliers")}, indent=2))


if __name__ == "__main__":
    main()
