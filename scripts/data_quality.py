EXPECTED = {"customers": 42_372, "theft": 3_615, "honest": 38_757, "start": "2014-01-01", "end": "2016-10-31"}


def longest_runs(mask: np.ndarray) -> np.ndarray:
    """Longest run of True in each row."""
    padded = np.zeros((mask.shape[0], mask.shape[1] + 2), dtype=np.int8)
    padded[:, 1:-1] = mask
    edges = np.diff(padded, axis=1)
    rows, starts = np.nonzero(edges == 1)
    _, ends = np.nonzero(edges == -1)
    longest = np.zeros(mask.shape[0], dtype=int)
    np.maximum.at(longest, rows, ends - starts)
    return longest


def assess(path: Path, cleaning: dict) -> dict:
    raw = pd.read_csv(path, low_memory=False)
    wide, labels = load_wide(str(path))
    W = wide.to_numpy(dtype=float)
    y = labels.reindex(wide.index).to_numpy().astype(int)
    missing = np.isnan(W)
    calendar = pd.date_range(EXPECTED["start"], EXPECTED["end"], freq="D")
    absent_dates = [d.strftime("%Y-%m-%d") for d in calendar.difference(wide.columns)]
    with np.errstate(invalid="ignore"):
        mean = np.nanmean(np.where(missing.all(axis=1, keepdims=True), 0.0, W), axis=1, keepdims=True)
        std = np.nanstd(np.where(missing.all(axis=1, keepdims=True), 0.0, W), axis=1, keepdims=True)
        sigma_outliers = int(((np.abs(W - mean) > 3 * std) & (std > 0)).sum())
    zero_runs = longest_runs(W == 0)
    missing_share = missing.mean(axis=1)
    _, cleaning_log = clean_series(wide, cleaning)

    return {
        "integrity": {
            "file": path.name,
            "file_size_mb": round(path.stat().st_size / 1e6, 1),
            "layout": f"wide: one row per customer, CONS_NO + FLAG + {wide.shape[1]:,} date columns",
            "rows_in_file": int(len(raw)),
            "duplicate_customer_rows": int(raw.duplicated(subset="CONS_NO").sum()),
            "customers": int(len(wide)),
            "days": int(wide.shape[1]),
            "calendar_days_in_range": int(len(calendar)),
            "absent_dates": absent_dates,
            "first_date": wide.columns[0].strftime("%Y-%m-%d"),
            "last_date": wide.columns[-1].strftime("%Y-%m-%d"),
            "cells": int(W.size),
        },
        "completeness": {
            "missing_cells": int(missing.sum()),
            "missing_percent": round(float(missing.mean() * 100), 2),
            "customers_complete": int((~missing.any(axis=1)).sum()),
            "customers_without_readings": int(missing.all(axis=1).sum()),
            "customers_over_10pct_missing": int((missing_share > 0.10).sum()),
            "theft_customers_over_10pct_missing": int(((missing_share > 0.10) & (y == 1)).sum()),
            "missing_percent_honest": round(float(missing[y == 0].mean() * 100), 2),
            "missing_percent_theft": round(float(missing[y == 1].mean() * 100), 2),
            "labels_missing": int(raw["FLAG"].isna().sum()),
        },
        "quality": {
            "negative_readings": int((W < 0).sum()),
            "readings_above_10000_kwh": int((W > 10_000).sum()),
            "readings_above_15000_kwh": int((W > 15_000).sum()),
            "max_reading_kwh": float(np.nanmax(W)),
            "median_reading_kwh": float(np.nanmedian(W)),
        },
        "class_distribution": {
            "honest": int((y == 0).sum()),
            "theft": int((y == 1).sum()),
            "theft_percent": round(float(y.mean() * 100), 2),
            "imbalance_ratio": round(float((y == 0).sum() / (y == 1).sum()), 2),
            "expected": EXPECTED,
        },
        "outliers": {
            "negative": int((W < 0).sum()),
            "above_10000_kwh": int((W > 10_000).sum()),
            "customers_with_zero_runs_over_30_days": int((zero_runs > 30).sum()),
            "cells_beyond_3_sd": sigma_outliers,
        },
        "preprocessing_log": cleaning_log,
    }


