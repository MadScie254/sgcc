        f"| Validity | Range 0–15,000 kWh | {q['readings_above_15000_kwh']:,} readings above 15,000 kWh; {q['readings_above_10000_kwh']:,} above 10,000 kWh; maximum {q['max_reading_kwh']:,.0f} kWh |",
        f"| Uniqueness | Duplicate customers | {i['duplicate_customer_rows']:,} duplicated rows |",
        "| Timeliness | Date sequence | Dates stored out of order in the header (e.g. 2014/1/1, 2014/1/10); sorted chronologically on load |",
        "",
        "## IV. Class distribution verification",
        "",
        "| Class | Expected count | Expected % | Actual count | Actual % |",
        "|---|---|---|---|---|",
        f"| Honest (0) | 38,757 | 91.5% | {d['honest']:,} | {100 - d['theft_percent']:.2f}% |",
        f"| Theft (1) | 3,615 | 8.5% | {d['theft']:,} | {d['theft_percent']:.2f}% |",
        f"| Imbalance ratio | 10.72 : 1 | | {d['imbalance_ratio']} : 1 | |",
        "",
        "## V. Outlier detection summary",
